const STORAGE_KEY = "lan.lang";

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in STRINGS) return saved;
  } catch {
    // Stockage indisponible (navigation privée…) : on se rabat sur la langue du navigateur.
  }
  return /^fr\b/i.test(navigator.language || "fr") ? "fr" : "en";
}

export let lang = initialLang();

export const locale = () => (lang === "fr" ? "fr-FR" : "en-GB");

export function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

const listeners = new Set();
export function onLangChange(fn) {
  listeners.add(fn);
}

// Textes fixes du HTML : data-i18n (texte), data-i18n-placeholder, data-i18n-aria, data-i18n-title.
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-lang]")) el.setAttribute("aria-pressed", String(el.dataset.lang === lang));
}

export function setLang(next) {
  if (!(next in STRINGS) || next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Préférence non mémorisée : la page reste quand même traduite.
  }
  applyStatic();
  for (const fn of listeners) fn();
}

export function initLangSwitch() {
  for (const button of document.querySelectorAll("[data-lang]")) {
    button.addEventListener("click", () => setLang(button.dataset.lang));
  }
  applyStatic();
}
